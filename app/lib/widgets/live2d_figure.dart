/// The callbacks a [Live2DHost] reports to.
class Live2DHostConfig {
  const Live2DHostConfig({
    required this.framing,
    required this.follow,
    required this.onReady,
    required this.onError,
  });

  /// `full` or `upper`.
  final String framing;

  /// The eyes follow the pointer; the frame then takes the pointer.
  final bool follow;

  /// The model is drawn.
  final VoidCallback onReady;

  /// No WebGL, a runtime or the model did not load, or it took too long.
  final void Function(String reason) onError;
}

/// What runs the model: on the web, an iframe with `web/live2d/index.html`.
abstract class Live2DHost {
  /// The model's view; transparent until it is ready.
  Widget get view;

  /// Posts one message to the page (`web/live2d/scene.js` lists them).
  void send(Map<String, Object?> message);

  void dispose();
}

/// Makes the host for one figure, or null where there is none (not the web).
typedef Live2DHostFactory = Live2DHost? Function(Live2DHostConfig config);

/// 大肥鱼 as a Live2D model (`web/live2d/`), with [fallback] shown until the
/// model is drawn, and instead of it when it cannot be: off the web, without
/// WebGL, when loading fails, and in tests.
///
/// * [mood] and [state] are sent to the model whenever they change; [wave]
///   waves once each time it turns true. [Live2DFigureState.react] plays a
///   short reaction.
/// * The box is [size] high and `size * Avatar.aspect` wide, like [Avatar].
/// * [framing] is `full` (the whole figure) or `upper` (head and chest).
/// * [follow] lets her eyes follow the pointer; only then does the figure
///   take pointer events, which otherwise pass through to what is under it.
class Live2DFigure extends StatefulWidget {
  const Live2DFigure({
    super.key,
    required this.mood,
    required this.state,
    this.wave = false,
    this.size = 160,
    this.framing = 'full',
    this.follow = false,
    this.fallback = const SizedBox.shrink(),
  });

  final AvatarMood mood;
  final AvatarState state;
  final bool wave;
  final double size;
  final String framing;
  final bool follow;
  final Widget fallback;

  /// Replaces the platform's host; tests use it to see the messages.
  @visibleForTesting
  static Live2DHostFactory? debugHostFactory;

  @override
  State<Live2DFigure> createState() => Live2DFigureState();
}

class Live2DFigureState extends State<Live2DFigure> {
  Live2DHost? _host;
  bool _ready = false;
  bool _failed = false;

  /// Messages waiting for the model to be ready.
  final List<Map<String, Object?>> _queue = [];

  /// Whether the model is drawn.
  bool get ready => _ready;

  @override
  void initState() {
    super.initState();
    final make = Live2DFigure.debugHostFactory ?? platform.createLive2DHost;
    _host = make(
      Live2DHostConfig(
        framing: widget.framing == 'upper' ? 'upper' : 'full',
        follow: widget.follow,
        onReady: _onReady,
        onError: _onError,
      ),
    );
    _send({'type': 'mood', 'mood': widget.mood.name});
    _send({'type': 'state', 'state': widget.state.name});
    if (widget.wave) _send({'type': 'wave'});
  }

  void _onReady() {
    if (!mounted || _failed || _ready) return;
    setState(() => _ready = true);
    final queued = List.of(_queue);
    _queue.clear();
    // Only the latest mood and state matter; every wave and reaction is played.
    for (var i = 0; i < queued.length; i++) {
      final type = queued[i]['type'];
      final later = queued.skip(i + 1).any((m) => m['type'] == type);
      if ((type == 'mood' || type == 'state') && later) continue;
      _host?.send(queued[i]);
    }
  }

  void _onError(String reason) {
    if (!mounted || _failed) return;
    debugPrint('Live2DFigure: $reason; showing the fallback');
    setState(() {
      _failed = true;
      _ready = false;
    });
    _queue.clear();
    _host?.dispose();
    _host = null;
  }

  void _send(Map<String, Object?> message) {
    if (_host == null || _failed) return;
    if (_ready) {
      _host!.send(message);
    } else {
      _queue.add(message);
    }
  }

  /// A short reaction: `surprised` or `happy`.
  void react(String kind) => _send({'type': 'react', 'kind': kind});

  @override
  void didUpdateWidget(Live2DFigure oldWidget) {
    super.didUpdateWidget(oldWidget);
    final old = oldWidget;
    if (old.mood != widget.mood) _send({'type': 'mood', 'mood': widget.mood.name});
    if (old.state != widget.state) _send({'type': 'state', 'state': widget.state.name});
    if (widget.wave && !old.wave) _send({'type': 'wave'});
  }

  @override
  void dispose() {
    _host?.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final host = _host;
    return SizedBox(
      width: widget.size * Avatar.aspect,
      height: widget.size,
      child: Stack(
        fit: StackFit.expand,
        children: [
          if (!_ready) widget.fallback,
          if (host != null) IgnorePointer(ignoring: !widget.follow, child: host.view),
        ],
      ),
    );
  }
}
