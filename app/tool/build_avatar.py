"""Packs the companion's animations (app/art/infinity/*.gif) into the atlas the app draws her from.

    pip install pillow
    python app/tool/build_avatar.py

Writes app/assets/infinity/infinity.webp (every kept frame, cropped to its clip's box and
shelf-packed) and app/lib/widgets/avatar_atlas.dart (where each frame sits in the atlas, how long
it is shown, and where her head is, for the chat badge). Rerun it after changing a GIF.

Each clip is cropped to the union of its frames' opaque pixels, so every frame of a clip shares one
box and the figure does not jump. Long clips keep every second frame (its time is added to the
frame before it); identical neighbouring frames are merged into one longer frame.
"""

import pathlib

from PIL import Image, ImageChops, ImageSequence

APP = pathlib.Path(__file__).resolve().parent.parent
SRC = APP / "art/infinity"
OUT_IMAGE = APP / "assets/infinity/infinity.webp"
OUT_DART = APP / "lib/widgets/avatar_atlas.dart"
ATLAS_WIDTH = 2048
PAD = 2

# name: (keep every n-th frame, head centre x, y and side in the GIF's own pixels)
CLIPS = {
    "idle": (1, 172, 165, 200),  # standing, full figure, blinks
    "cheer": (2, 118, 100, 110),  # fists up, fired up
    "success": (1, 113, 112, 115),  # check mark, +100 XP
    "wave": (2, 118, 110, 115),  # waves hello
    "sleep": (2, 100, 100, 120),  # asleep on a cloud
    "study": (2, 118, 118, 115),  # reads her book
}


def frames_of(path):
    """The GIF's frames as RGBA images with their durations (ms)."""
    im = Image.open(path)
    out = []
    for frame in ImageSequence.Iterator(im):
        out.append((frame.convert("RGBA"), int(frame.info.get("duration") or 100)))
    return out


def union_box(frames):
    box = None
    for image, _ in frames:
        b = image.getchannel("A").getbbox()
        if b is None:
            continue
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    return box


def thin(frames, step):
    """Every step-th frame; dropped frames' time goes to the kept one before them."""
    kept = []
    for i, (image, ms) in enumerate(frames):
        if i % step == 0:
            kept.append([image, ms, i])
        else:
            kept[-1][1] += ms
    merged = []
    for image, ms, i in kept:
        if merged and ImageChops.difference(merged[-1][0], image).getbbox(alpha_only=False) is None:
            merged[-1][1] += ms
        else:
            merged.append([image, ms, i])
    return merged


def main():
    clips = {}
    for name, (step, hx, hy, side) in CLIPS.items():
        frames = frames_of(SRC / f"{name}.gif")
        box = union_box(frames)
        cropped = [(image.crop(box), ms) for image, ms in frames]
        clips[name] = {
            "box": box,
            "frames": thin(cropped, step),
            "head": (hx - box[0], hy - box[1], side),
            "source_count": len(frames),
        }

    # Shelf packing, one clip after another.
    x = y = shelf = 0
    for clip in clips.values():
        w = clip["box"][2] - clip["box"][0]
        h = clip["box"][3] - clip["box"][1]
        clip["size"] = (w, h)
        clip["rects"] = []
        for _ in clip["frames"]:
            if x + w > ATLAS_WIDTH:
                x, y, shelf = 0, y + shelf + PAD, 0
            clip["rects"].append((x, y))
            x += w + PAD
            shelf = max(shelf, h)
    height = y + shelf

    atlas = Image.new("RGBA", (ATLAS_WIDTH, height), (0, 0, 0, 0))
    for clip in clips.values():
        for (image, _, _), (fx, fy) in zip(clip["frames"], clip["rects"]):
            atlas.alpha_composite(image, (fx, fy))
    OUT_IMAGE.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(OUT_IMAGE, "WEBP", quality=88, alpha_quality=100, method=6)

    lines = [
        "// GENERATED by tool/build_avatar.py from art/infinity/*.gif; do not edit.",
        "",
        "import 'dart:ui';",
        "",
        "/// One picture of a clip: where it sits in the atlas and how long it is shown.",
        "class AtlasFrame {",
        "  const AtlasFrame(this.source, this.ms, this.original);",
        "",
        "  /// The frame's box in `assets/infinity/infinity.webp`.",
        "  final Rect source;",
        "",
        "  /// How long it is shown.",
        "  final int ms;",
        "",
        "  /// Its index in the source GIF.",
        "  final int original;",
        "}",
        "",
        "/// One animation, cropped to the box all its frames share.",
        "class AtlasClip {",
        "  const AtlasClip({required this.width, required this.height, required this.head, required this.frames});",
        "",
        "  /// The shared box, in atlas pixels.",
        "  final double width;",
        "  final double height;",
        "",
        "  /// A square around her head, in the box's pixels (the chat badge).",
        "  final Rect head;",
        "",
        "  final List<AtlasFrame> frames;",
        "}",
        "",
        f"const String atlasAsset = 'assets/infinity/infinity.webp';",
        "",
    ]
    for name, clip in clips.items():
        w, h = clip["size"]
        hx, hy, side = clip["head"]
        lines.append(
            f"// {name}.gif: {clip['source_count']} frames, box {clip['box']}, {len(clip['frames'])} kept."
        )
        lines.append(f"const AtlasClip {name}Clip = AtlasClip(")
        lines.append(f"  width: {w},")
        lines.append(f"  height: {h},")
        lines.append(f"  head: Rect.fromLTWH({hx - side / 2}, {hy - side / 2}, {side}, {side}),")
        lines.append("  frames: [")
        for (_, ms, original), (fx, fy) in zip(clip["frames"], clip["rects"]):
            lines.append(f"    AtlasFrame(Rect.fromLTWH({fx}, {fy}, {w}, {h}), {ms}, {original}),")
        lines.append("  ],")
        lines.append(");")
        lines.append("")
    OUT_DART.write_text("\n".join(lines), encoding="utf-8")

    total = sum(len(c["frames"]) for c in clips.values())
    print(f"{OUT_IMAGE.name}: {ATLAS_WIDTH}x{height}, {total} frames, {OUT_IMAGE.stat().st_size // 1024} KiB")
    for name, clip in clips.items():
        print(f"  {name}: {[(o, ms) for _, ms, o in clip['frames']]}")


if __name__ == "__main__":
    main()
