def fetch(url: str, path: pathlib.Path) -> pathlib.Path:
    """[path], downloading [url] into it first if it is not cached yet."""
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        print("downloading", url)
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read()
        tmp = path.with_suffix(path.suffix + ".part")
        tmp.write_bytes(data)
        tmp.replace(path)
    return path


def clean_step(text: str) -> str:
    """A dataset instruction trimmed, its inner line breaks and runs of spaces collapsed, and a
    stray leading "6. " numbering dropped."""
    text = re.sub(r"\s+", " ", text).strip()
    return re.sub(r"^\d+\.\s+", "", text)


def body_of(x: dict) -> str:
    if x["category"] == "cardio":
        return "cardio"
    if x["category"] == "stretching":
        return "stretch"
    return BODY_BY_MUSCLE[x["primaryMuscles"][0]]


def unit_of(x: dict) -> str:
    if x["category"] == "stretching" or x["id"] in TIMED_STRENGTH:
        return "time"
    if x["category"] == "cardio":
        return "distance" if x["id"] in DISTANCE_CARDIO else "time"
    return "reps"


def frame(src: pathlib.Path, dst: pathlib.Path) -> None:
    with Image.open(src) as image:
        image = image.convert("RGB")
        height = round(image.height * WIDTH / image.width)
        image = image.resize((WIDTH, height), Image.LANCZOS)
        image.save(dst, "WEBP", quality=QUALITY, method=6)


def main() -> None:
    dataset = json.loads(fetch(f"{RAW}/dist/exercises.json", CACHE / "exercises.json").read_text())
    by_id = {x["id"]: x for x in dataset}
    IMG.mkdir(parents=True, exist_ok=True)

    library, catalog_seen = [], set()
    for exercise_id, row in EXERCISES.items():
        x = by_id[exercise_id]
        steps_en = [clean_step(s) for s in x["instructions"] if s.strip()]
        assert steps_en, f"{exercise_id}: no instructions upstream"
        assert len(steps_en) == len(row["ko_steps"]) == len(row["zh_steps"]), (
            f"{exercise_id}: {len(steps_en)} en / {len(row['ko_steps'])} ko / {len(row['zh_steps'])} zh steps")
        assert len(x["images"]) >= 2, f"{exercise_id}: fewer than two images"
        if row["catalog"]:
            assert row["catalog"] not in catalog_seen, f"{row['catalog']} matched twice"
            catalog_seen.add(row["catalog"])

        images = []
        for n in (0, 1):
            src = fetch(f"{RAW}/exercises/{exercise_id}/{n}.jpg", CACHE / exercise_id / f"{n}.jpg")
            name = f"{exercise_id}_{n}.webp"
            frame(src, IMG / name)
            images.append(name)

        muscles = list(dict.fromkeys(x["primaryMuscles"] + x["secondaryMuscles"]))
        library.append({
            "id": exercise_id,
            "name": {"en": row["en"] or x["name"].strip(), "ko": row["ko"], "zh": row["zh"]},
            "body": body_of(x),
            "category": CATEGORY[x["category"]],
            "equipment": EQUIPMENT[x["equipment"]],
            "level": x["level"],
            "muscles": muscles,
            "unit": unit_of(x),
            "steps": {"en": steps_en, "ko": row["ko_steps"], "zh": row["zh_steps"]},
            "images": images,
            "catalog": row["catalog"],
        })

    keep = {name for item in library for name in item["images"]}
    for stale in IMG.glob("*.webp"):
        if stale.name not in keep:
            stale.unlink()

    (OUT / "library.json").write_text(json.dumps(library, ensure_ascii=False, indent=2) + "\n")
    counts = {body: sum(1 for item in library if item["body"] == body) for body in BODIES}
    size = sum(p.stat().st_size for p in IMG.glob("*.webp"))
    print(f"{len(library)} exercises {counts}; images {size / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
